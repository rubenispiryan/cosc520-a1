"""Create lookup-time and filter-accuracy plots from a summary CSV."""

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import PercentFormatter


LABELS = {
    "linear_search": "Linear search",
    "binary_search": "Binary search",
    "hash_table": "Hash table",
    "bloom_filter": "Bloom filter",
    "cuckoo_filter": "Cuckoo filter",
}
ORDER = tuple(LABELS)


def _load_summary(path: Path) -> List[Dict[str, str]]:
    """Read the CSV summary rows.

    Args:
        path: Summary CSV generated by `benchmark`.

    Returns:
        A list of row dictionaries.
    """
    with path.open("r", encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def _save_lookup_plot(groups, output_path: Path, log_scale: bool, title: str) -> None:
    """Save one per-query runtime chart as PNG and PDF."""
    figure, axis = plt.subplots(figsize=(8.2, 5.2))
    for algorithm in ORDER:
        rows = groups.get(algorithm, [])
        if not rows:
            continue
        rows = sorted(rows, key=lambda row: int(row["n"]))
        sizes = [int(row["n"]) for row in rows]
        times_us = [float(row["median_ns_per_query"]) / 1_000 for row in rows]
        axis.plot(sizes, times_us, marker="o", linewidth=1.7, markersize=4,
                  label=LABELS[algorithm])
    axis.set_xlabel("Number of stored usernames (n)")
    axis.set_ylabel("Median lookup time (microseconds per query)")
    axis.set_title(title)
    if log_scale:
        axis.set_xscale("log")
        axis.set_yscale("log")
    axis.grid(True, which="both", alpha=0.25)
    axis.legend()
    figure.tight_layout()
    for extension in ("png", "pdf"):
        figure.savefig(output_path.with_suffix("." + extension), dpi=180)
    plt.close(figure)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Plot median lookup times and observed filter false-positive rates.

    Args:
        argv: Optional command-line arguments for testing or embedding.

    Returns:
        Process exit status, zero on success.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path, help="benchmark summary CSV")
    parser.add_argument("--out-dir", type=Path, default=Path("plots"))
    parser.add_argument("--title-suffix", default="", help="optional run label for chart titles")
    args = parser.parse_args(argv)
    if not args.input.exists():
        parser.error("summary CSV not found: {}".format(args.input))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    rows = _load_summary(args.input)
    if not rows:
        parser.error("summary CSV has no measured rows")
    groups = defaultdict(list)
    for row in rows:
        groups[row["algorithm"]].append(row)

    linear_rows = groups.get("linear_search", [])
    if linear_rows:
        shared_max_n = max(int(row["n"]) for row in linear_rows)
        shared_groups = {
            algorithm: [row for row in selected if int(row["n"]) <= shared_max_n]
            for algorithm, selected in groups.items()
        }
    else:
        shared_groups = groups
    _save_lookup_plot(
        shared_groups, args.out_dir / "lookup_time_per_query_linear", log_scale=False,
        title="Membership lookup time: shared range{}".format(args.title_suffix),
    )
    _save_lookup_plot(
        groups, args.out_dir / "lookup_time_per_query_log", log_scale=True,
        title="Membership lookup time: all measured sizes{}".format(args.title_suffix),
    )

    filter_rows = [
        row for row in rows
        if row["algorithm"] in ("bloom_filter", "cuckoo_filter")
        and row["accuracy_false_positive_rate"] != ""
    ]
    if filter_rows:
        figure, axis = plt.subplots(figsize=(8.2, 5.2))
        for algorithm in ("bloom_filter", "cuckoo_filter"):
            selected = sorted(
                (row for row in filter_rows if row["algorithm"] == algorithm),
                key=lambda row: int(row["n"]),
            )
            if not selected:
                continue
            axis.plot(
                [int(row["n"]) for row in selected],
                [float(row["accuracy_false_positive_rate"]) for row in selected],
                marker="o", linewidth=1.7, markersize=4, label=LABELS[algorithm],
            )
        axis.set_xlabel("Number of stored usernames (n)")
        axis.set_ylabel("Observed false-positive rate")
        axis.set_title("Filter Accuracy on Seeded Random Absent Queries{}".format(args.title_suffix))
        axis.set_xscale("log")
        axis.yaxis.set_major_formatter(PercentFormatter(1.0))
        target_rates = {
            float(row["target_false_positive_rate"])
            for row in filter_rows
            if row["algorithm"] == "bloom_filter" and row["target_false_positive_rate"]
        }
        if len(target_rates) == 1:
            axis.axhline(target_rates.pop(), color="gray", linestyle="--",
                         linewidth=1.2, label="Bloom target")
        axis.grid(True, which="both", alpha=0.25)
        axis.legend()
        figure.tight_layout()
        for extension in ("png", "pdf"):
            figure.savefig(args.out_dir / ("filter_false_positive_rate." + extension), dpi=180)
        plt.close(figure)

    print("Wrote plots to {}".format(args.out_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
